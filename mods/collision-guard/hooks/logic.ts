// Pure helpers: who edited what and when, which sessions are alive, and how to describe them.
// No `$` here, so tests can call them directly.

import type { EditRecord, SessionRecord, Step, StepStatus } from '../types'

export const COLLISION_WINDOW_MS = 30 * 60_000
// A session writes its record every 15 seconds; one silent for longer than this has gone away.
export const ALIVE_MS = 90_000
// Records of ended sessions are kept this long, so their recent edits still count, then removed.
export const KEEP_ENDED_MS = 24 * 3_600_000

export const CHOICES = ['Proceed', 'Move to a worktree', 'Cancel'] as const

// The folder name a project's records live under.
export function projectKey(root: string): string {
  return root.replace(/[^a-zA-Z0-9]/g, '-')
}

export function newRecord(sessionId: string, root: string, now: number): SessionRecord {
  return { sessionId, root, task: null, steps: [], isWorking: false, startedAt: now, updatedAt: now, isEnded: false, edits: [] }
}

export function recordEdit(edits: readonly EditRecord[], path: string, now: number): EditRecord[] {
  return [...edits.filter(e => e.path !== path && now - e.at < COLLISION_WINDOW_MS), { path, at: now }]
}

// The most recent edit of `path` by another session within the window, if any.
export function recentEditBy(
  records: readonly SessionRecord[],
  selfId: string,
  path: string,
  now: number,
): { record: SessionRecord; at: number } | undefined {
  let found: { record: SessionRecord; at: number } | undefined
  for (const record of records) {
    if (record.sessionId === selfId) continue
    for (const edit of record.edits) {
      if (edit.path === path && now - edit.at < COLLISION_WINDOW_MS && (!found || edit.at > found.at)) {
        found = { record, at: edit.at }
      }
    }
  }
  return found
}

// Whether to ask: there is a recent edit, and the person has not already gone ahead past that very edit.
export function shouldAsk(hit: { at: number } | undefined, clearedAt: number | undefined): boolean {
  return hit !== undefined && (clearedAt === undefined || hit.at > clearedAt)
}

export function liveOthers(records: readonly SessionRecord[], selfId: string, now: number): SessionRecord[] {
  return records
    .filter(r => r.sessionId !== selfId && !r.isEnded && now - r.updatedAt < ALIVE_MS)
    .sort((a, b) => a.startedAt - b.startedAt)
}

export function isStale(record: SessionRecord, now: number): boolean {
  return now - record.updatedAt > KEEP_ENDED_MS
}

export type WorkState = 'in progress' | 'waiting for input' | 'done'

// Working now: in progress. Stopped with unfinished steps: waiting. Stopped otherwise: its last request is done.
export function workState(record: SessionRecord): WorkState {
  if (record.isWorking) return 'in progress'
  if (record.steps.some(s => s.status !== 'completed')) return 'waiting for input'
  return 'done'
}

export function currentStep(record: SessionRecord): string | undefined {
  return record.steps.find(s => s.status === 'in_progress')?.content
}

export function describe(record: SessionRecord): string {
  const task = record.task ?? 'no request yet'
  return `"${task}" (session ${record.sessionId.slice(0, 8)})`
}

export function formatAgo(ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000))
  if (s < 60) return `${s} s ago`
  const m = Math.round(s / 60)
  return m < 60 ? `${m} min ago` : `${Math.floor(m / 60)} h ${m % 60} min ago`
}

export function shortPath(path: string, root: string): string {
  return path.startsWith(`${root}/`) ? path.slice(root.length + 1) : path
}

export function firstLine(text: string): string | null {
  const line = text.trim().split('\n')[0]?.trim() ?? ''
  if (line === '') return null
  return line.length > 120 ? `${line.slice(0, 117)}…` : line
}

// What the edit hook tells Claude when the person does not proceed.
export function denyReason(choice: string, otherLabel: string, file: string, ago: string): string {
  if (choice === 'Move to a worktree') {
    return `The user chose not to edit ${file} here, because another Claude session working on ${otherLabel} changed it ${ago}. Move this work into a git worktree: use the EnterWorktree tool to create one, bring over the changes you have already made for this task, then make this edit there.`
  }
  if (choice === 'Cancel') {
    return `The user cancelled this edit of ${file}: another Claude session working on ${otherLabel} changed it ${ago}. Do not edit this file; stop and ask the user how to proceed.`
  }
  return `The user did not let this edit of ${file} go ahead (another Claude session working on ${otherLabel} changed it ${ago}) and said: ${choice}`
}

// --- The session's task list, from whichever task-list tool Claude uses ---

function asStatus(status: unknown): StepStatus {
  return status === 'completed' || status === 'in_progress' ? status : 'pending'
}

export function applyUpdatePlan(
  steps: readonly Step[],
  input: { items?: ReadonlyArray<{ content: string; status: string }>; advance?: boolean; done?: readonly number[]; start?: number },
): Step[] {
  let next: Step[] = input.items ? input.items.map(i => ({ content: i.content, status: asStatus(i.status) })) : steps.map(s => ({ ...s }))
  if (input.advance) {
    const current = next.findIndex(s => s.status === 'in_progress')
    if (current >= 0) next[current] = { ...next[current]!, status: 'completed' }
    const after = next.findIndex((s, n) => n > current && s.status === 'pending')
    if (after >= 0) next[after] = { ...next[after]!, status: 'in_progress' }
  }
  for (const n of input.done ?? []) if (next[n - 1]) next[n - 1] = { ...next[n - 1]!, status: 'completed' }
  if (input.start !== undefined && next[input.start - 1]) {
    const at = input.start - 1
    next = next.map((s, n) => (n === at ? { ...s, status: 'in_progress' } : s.status === 'in_progress' ? { ...s, status: 'pending' } : s))
  }
  return next
}

export function applyTodoWrite(todos: ReadonlyArray<{ content: string; status: string }>): Step[] {
  return todos.map(t => ({ content: t.content, status: asStatus(t.status) }))
}

export function applyTaskUpdate(steps: readonly Step[], u: { taskId: string; status?: string; subject?: string }): Step[] {
  if (u.status === 'deleted') return steps.filter(s => s.id !== u.taskId)
  return steps.map(s => (s.id === u.taskId ? { ...s, content: u.subject ?? s.content, status: u.status ? asStatus(u.status) : s.status } : s))
}

export function parseRecord(text: string): SessionRecord | undefined {
  try {
    const r = JSON.parse(text)
    return typeof r?.sessionId === 'string' && typeof r?.updatedAt === 'number' && Array.isArray(r?.edits)
      ? (r as SessionRecord)
      : undefined
  } catch {
    return undefined
  }
}
